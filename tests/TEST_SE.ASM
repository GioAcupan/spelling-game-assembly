; TEST_SE.ASM — Smoke test for SCR_END module (v1.3)
; Exercises SCR_END_RUN in 2P mode: both players displayed,
; winner determined, leaderboard inserted + rendered.
; Build: BUILD.BAT TEST_SE → bin\TEST_SE.EXE

.MODEL SMALL
.DATA
    INCLUDE SHARED.INC

    ; --- State vars (normally in MAIN.ASM) ---
    PUBLIC CURRENT_STATE, NUM_PLAYERS
    PUBLIC PLAYER_NAMES, SCORES, HEARTS_ARR
    PUBLIC DIFFICULTY, LEADERBOARD
    PUBLIC USER_TABLE, USER_COUNT

    CURRENT_STATE   DB STATE_END
    NUM_PLAYERS     DB 2
    PLAYER_NAMES    DB 'AAA', 'BBB'
    SCORES          DW 150, 90
    HEARTS_ARR      DB MAX_HEARTS, MAX_HEARTS
    DIFFICULTY      DB DIFF_EASY
    LEADERBOARD     DB LB_MAX_ENTRIES * LB_ENTRY_SIZE DUP(0)
    USER_TABLE      DB MAX_USERS * USER_RECORD_SIZE DUP(0)
    USER_COUNT      DB 0

    ; --- GFX + Input + Audio deps (called from MAIN) ---

.CODE
    EXTRN SCR_END_RUN:PROC
    EXTRN GFX_INIT:PROC, GFX_SHUTDOWN:PROC
    EXTRN GFX_LOAD_BG:PROC, GFX_CLEAR:PROC, GFX_DRAW_STRING:PROC
    EXTRN INP_WAIT_KEY:PROC
    EXTRN SND_PLAY_PATTERN:PROC
    EXTRN FILE_INSERT_SCORE:PROC, FILE_SAVE_SCORES:PROC

MAIN PROC
    MOV  AX, @DATA
    MOV  DS, AX

    CALL GFX_INIT

    CALL SCR_END_RUN

    CMP  CURRENT_STATE, STATE_QUIT
    JNE  TSE_WAIT

TSE_EXIT:
    CALL GFX_SHUTDOWN
    MOV  AH, 4Ch
    MOV  AL, 0
    INT  21h

TSE_WAIT:
    CALL INP_WAIT_KEY
    JMP  TSE_EXIT
MAIN ENDP

END MAIN
