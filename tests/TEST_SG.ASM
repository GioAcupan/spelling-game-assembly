; TEST_SG.ASM — Smoke test for SCR_GAME module
; Exercises SCR_ROUND_RUN and SCR_JUDGE_RUN with minimal setup.
; Build: BUILD.BAT TEST_SG → bin\TEST_SG.EXE

.MODEL SMALL
.DATA
    INCLUDE SHARED.INC

    ; --- State vars (normally in MAIN.ASM) ---
    PUBLIC CURRENT_STATE, CURRENT_WORD
    PUBLIC NUM_PLAYERS, CURRENT_PLAYER
    PUBLIC DIFFICULTY, TIMER_START
    PUBLIC PLAYER_NAMES, SCORES, HEARTS_ARR
    PUBLIC PLAYER_RESULTS, PLAYER_TIMES
    PUBLIC INPUT_BUFFER

    CURRENT_STATE   DB STATE_ROUND
    CURRENT_WORD    DB 0
    NUM_PLAYERS     DB 1
    CURRENT_PLAYER  DB 0
    DIFFICULTY      DB DIFF_EASY
    TIMER_START     DW 0
    PLAYER_NAMES    DB 'AAA', 'BBB'
    SCORES          DW 0, 0
    HEARTS_ARR      DB MAX_HEARTS, MAX_HEARTS
    PLAYER_RESULTS  DB 0, 0
    PLAYER_TIMES    DW 0, 0
    INPUT_BUFFER    DB 17 DUP(0)

.CODE
    EXTRN GFX_INIT:PROC, GFX_SHUTDOWN:PROC
    EXTRN SCR_ROUND_RUN:PROC, SCR_JUDGE_RUN:PROC
    EXTRN GFX_LOAD_BG:PROC, GFX_CLEAR:PROC
    EXTRN GFX_DRAW_SPRITE:PROC, GFX_DRAW_CHAR:PROC, GFX_DRAW_STRING:PROC
    EXTRN INP_WAIT_KEY:PROC, INP_CHECK_KEY:PROC, INP_READ_STRING:PROC
    EXTRN SND_PLAY_PATTERN:PROC, SND_DELAY:PROC

MAIN PROC
    MOV  AX, @DATA
    MOV  DS, AX

    CALL GFX_INIT

    ; --- Run game loop ---
TST_LOOP:
    CMP  CURRENT_STATE, STATE_ROUND
    JNE  TST_CHECK_JUDGE
    CALL SCR_ROUND_RUN
    JMP  TST_CHECK_DONE

TST_CHECK_JUDGE:
    CMP  CURRENT_STATE, STATE_JUDGE
    JNE  TST_CHECK_DONE
    CALL SCR_JUDGE_RUN

TST_CHECK_DONE:
    CMP  CURRENT_STATE, STATE_END
    JE   TST_EXIT
    CMP  CURRENT_STATE, STATE_QUIT
    JE   TST_EXIT
    JMP  TST_LOOP

TST_EXIT:
    CALL GFX_SHUTDOWN
    MOV  AH, 4Ch
    MOV  AL, 0
    INT  21h
MAIN ENDP

END MAIN
