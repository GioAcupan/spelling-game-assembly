; TEST_SCI.ASM — Smoke test for SCRINTRO.ASM
; Walks through all 6 intro screens: TITLE → LOGIN → MODE → NAME → DIFF → INSTR
; Link: TEST_SCI.OBJ + SCRINTRO.OBJ + GFX.OBJ + INPUT.OBJ + AUDIO.OBJ + FILEIO.OBJ + DATA.OBJ

.MODEL SMALL
.STACK 1024

.DATA
    INCLUDE SHARED.INC

    ; --- Runtime state (standalone copies — no MAIN.ASM linked) ---
    CURRENT_STATE   DB  STATE_TITLE
    NUM_PLAYERS     DB  1
    CURRENT_PLAYER  DB  0
    DIFFICULTY      DB  DIFF_EASY
    CURRENT_WORD    DB  0
    TIMER_START     DW  0

    ; --- Leaderboard ---
    LEADERBOARD     DB  LB_MAX_ENTRIES * LB_ENTRY_SIZE DUP(0)

    ; --- Login / user account state ---
    SESSION_USER    DB  '   '
    USER_TABLE      DB  MAX_USERS * USER_RECORD_SIZE DUP(0)
    USER_COUNT      DB  0
    LOGIN_RETRIES   DB  0
    USERNAME_BUF    DB  3 DUP(0)
    PASSWORD_BUF    DB  5 DUP(0)

    ; --- Player-indexed arrays ---
    PLAYER_NAMES    DB  '   ', '   '
    SCORES          DW  0, 0
    HEARTS_ARR      DB  MAX_HEARTS, MAX_HEARTS
    PLAYER_RESULTS  DB  0, 0
    PLAYER_TIMES    DW  0, 0
    INPUT_BUFFER    DB  17 DUP(0)

    ; --- Test helper strings ---
    STR_DONE        DB 'ALL SCREENS PASSED! PRESS KEY...',0
    STR_PRESS       DB 'PRESS ANY KEY TO START',0

    PUBLIC CURRENT_STATE, NUM_PLAYERS, CURRENT_PLAYER, DIFFICULTY
    PUBLIC CURRENT_WORD, TIMER_START
    PUBLIC LEADERBOARD, SESSION_USER, USER_TABLE, USER_COUNT, LOGIN_RETRIES
    PUBLIC USERNAME_BUF, PASSWORD_BUF
    PUBLIC PLAYER_NAMES, SCORES, HEARTS_ARR, PLAYER_RESULTS, PLAYER_TIMES
    PUBLIC INPUT_BUFFER

.CODE
    EXTRN GFX_INIT:PROC, GFX_SHUTDOWN:PROC, GFX_CLEAR:PROC
    EXTRN GFX_LOAD_BG:PROC, GFX_DRAW_STRING:PROC, GFX_DRAW_CHAR:PROC
    EXTRN INP_WAIT_KEY:PROC
    EXTRN SND_PLAY_PATTERN:PROC, SND_DELAY:PROC, SND_SILENCE:PROC
    EXTRN FILE_LOAD_SCORES:PROC, FILE_SAVE_SCORES:PROC
    EXTRN FILE_INSERT_SCORE:PROC
    EXTRN USER_AUTH:PROC, USER_SAVE:PROC, USER_LOAD:PROC
    EXTRN SCR_TITLE_RUN:PROC, SCR_LOGIN_RUN:PROC, SCR_MODE_RUN:PROC
    EXTRN SCR_NAME_RUN:PROC, SCR_DIFF_RUN:PROC, SCR_INSTR_RUN:PROC

MAIN PROC
    MOV  AX, @DATA
    MOV  DS, AX

    ; --- Init ---
    CALL GFX_INIT
    CALL FILE_LOAD_SCORES
    CALL USER_LOAD

    ; --- Start screen ---
    MOV  AL, 1
    CALL GFX_CLEAR
    LEA  SI, STR_PRESS
    MOV  BL, 15
    MOV  CX, 60
    MOV  DX, 80
    CALL GFX_DRAW_STRING
    CALL INP_WAIT_KEY

    ; === Screen 1: TITLE ===
    MOV  CURRENT_STATE, STATE_TITLE
    CALL SCR_TITLE_RUN
    ; After SCR_TITLE_RUN, CURRENT_STATE should be STATE_LOGIN

    ; === Screen 2: LOGIN ===
    ; SCR_LOGIN_RUN internally handles auth loop, exits to STATE_MODE or STATE_TITLE
    CALL SCR_LOGIN_RUN
    ; Bail to done if login redirected to TITLE (USERS.DAT full or 3 wrong attempts)
    CMP  CURRENT_STATE, STATE_TITLE
    JE   TEST_DONE

    ; === Screen 3: MODE ===
    ; SCR_MODE_RUN sets NUM_PLAYERS, pre-fills PLAYER_NAMES[0] from SESSION_USER
    CALL SCR_MODE_RUN
    ; 1P → STATE_DIFF, 2P → STATE_NAME

    ; === Screen 4: NAME (only if 2P — CURRENT_STATE = STATE_NAME) ===
    CMP  CURRENT_STATE, STATE_NAME
    JNE  SKIP_NAME
    CALL SCR_NAME_RUN
    ; SCR_NAME_RUN loops internally via state machine; exits to STATE_DIFF
SKIP_NAME:

    ; === Screen 5: DIFFICULTY ===
    CALL SCR_DIFF_RUN
    ; Exits to STATE_INSTR

    ; === Screen 6: INSTRUCTIONS ===
    CALL SCR_INSTR_RUN
    ; Exits to STATE_ROUND

TEST_DONE:
    ; --- Done — clear screen and show result ---
    MOV  AL, 0
    CALL GFX_CLEAR
    LEA  SI, STR_DONE
    MOV  BL, 10
    MOV  CX, 40
    MOV  DX, 90
    CALL GFX_DRAW_STRING
    CALL INP_WAIT_KEY

    ; --- Shutdown ---
    CALL GFX_SHUTDOWN
    MOV  AH, 4Ch
    MOV  AL, 0
    INT  21h
MAIN ENDP

END MAIN
